const cor = "vermelho";

switch (cor) {
    case "azul":
        console.log("A cor é azul.");
        break;
    case "vermelho":
        console.log("A cor é vermelha.");
        break;
    case "verde":
        console.log("A cor é verde.");
        break;
    default:
        console.log("A cor não é azul, vermelha ou verde.");
}